"""
Generate a GMAT script that numerically propagates every satellite of tle.txt and
writes their EarthMJ2000Eq positions to a ReportFile readable by validate_geometry.py.

GMAT has no SGP4 propagator, so the initial state of each satellite is the SGP4
osculating state at the epoch (TEME), rotated to GCRS (~ EarthMJ2000Eq) with astropy.
From there GMAT integrates with its own force model -> genuinely independent dynamics.
Expect SGP4 vs numerical to drift (km-level per day in LEO): use the looser
--tol-range-km-gmat / --tol-edge-s-gmat tolerances in the validator.

Usage (from satgenpy/satgen/edrs):
    python -m validation.make_gmat_script --duration 86400 --step 10
    GmatConsole -r validation/gmat/edrs_validation.script     (or open in the GMAT GUI and Run)
    python -m validation.validate_geometry --gmat validation/gmat/report_edrs.txt
"""
import argparse
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
EDRS = os.path.dirname(HERE)
SATGENPY = os.path.abspath(os.path.join(EDRS, "..", ".."))
for p in (SATGENPY, EDRS):
    if p not in sys.path:
        sys.path.insert(0, p)

from astropy import units as u                                            # noqa: E402
from astropy.coordinates import TEME, GCRS, CartesianRepresentation, CartesianDifferential  # noqa: E402
from sgp4.api import Satrec, jday                                         # noqa: E402

from validation.geometry import read_hypatia_tles                         # noqa: E402
from satgen.edrs.config import conf                                       # noqa: E402

MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()


def teme_to_gcrs(r_km, v_kms, t):
    teme = TEME(CartesianRepresentation(r_km * u.km, differentials=CartesianDifferential(v_kms * u.km / u.s)),
                obstime=t)
    g = teme.transform_to(GCRS(obstime=t))
    r = g.cartesian.xyz.to_value(u.km)
    v = g.cartesian.differentials["s"].d_xyz.to_value(u.km / u.s)
    return r, v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tle", default=os.path.join(EDRS, "src", "tles", "tle.txt"))
    ap.add_argument("--duration", type=float, default=86400.0)
    ap.add_argument("--step", type=float, default=10.0)
    ap.add_argument("--degree", type=int, default=8, help="Earth gravity degree/order (JGM-3)")
    ap.add_argument("--third-body", action="store_true", help="add Sun & Moon point masses")
    ap.add_argument("--out", default=os.path.join(HERE, "gmat"))
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)

    t0 = conf.epoch.utc
    dt = t0.datetime
    jd, fr = jday(dt.year, dt.month, dt.day, dt.hour, dt.minute, dt.second)
    gmat_epoch = f"{dt.day:02d} {MONTHS[dt.month - 1]} {dt.year} {dt.hour:02d}:{dt.minute:02d}:{dt.second:02d}.000"

    tles = read_hypatia_tles(args.tle)
    names = [f"Sat{i}" for i in range(len(tles))]
    report = os.path.abspath(os.path.join(args.out, "report_edrs.txt"))

    s = [f"% Auto-generated by make_gmat_script.py from {os.path.basename(args.tle)}",
         f"% Epoch {t0.iso} UTC, duration {args.duration:.0f} s, fixed step {args.step:g} s", ""]
    for name, (label, l1, l2) in zip(names, tles):
        e, r, v = Satrec.twoline2rv(l1, l2).sgp4(jd, fr)
        if e:
            raise RuntimeError(f"SGP4 error {e} for {label}")
        rg, vg = teme_to_gcrs(np.array(r), np.array(v), t0)
        s += [f"% {label}",
              f"Create Spacecraft {name};",
              f"{name}.DateFormat = UTCGregorian;",
              f"{name}.Epoch = '{gmat_epoch}';",
              f"{name}.CoordinateSystem = EarthMJ2000Eq;",
              f"{name}.DisplayStateType = Cartesian;",
              f"{name}.X = {rg[0]:.9f};", f"{name}.Y = {rg[1]:.9f};", f"{name}.Z = {rg[2]:.9f};",
              f"{name}.VX = {vg[0]:.12f};", f"{name}.VY = {vg[1]:.12f};", f"{name}.VZ = {vg[2]:.12f};", ""]

    pm = "{Luna, Sun}" if args.third_body else "{}"
    s += ["Create ForceModel FM;",
          "FM.CentralBody = Earth;",
          "FM.PrimaryBodies = {Earth};",
          f"FM.PointMasses = {pm};",
          "FM.Drag = None;",
          "FM.SRP = Off;",
          f"FM.GravityField.Earth.Degree = {args.degree};",
          f"FM.GravityField.Earth.Order = {args.degree};",
          "FM.GravityField.Earth.PotentialFile = 'JGM3.cof';",
          "",
          "Create Propagator Prop;",
          "Prop.FM = FM;",
          "Prop.Type = RungeKutta89;",
          f"Prop.InitialStepSize = {args.step:g};",
          f"Prop.MinStep = {args.step:g};",
          f"Prop.MaxStep = {args.step:g};",
          "Prop.ErrorControl = None;     % fixed step -> uniform report rows",
          "",
          "Create ReportFile RF;",
          f"RF.Filename = '{report}';",
          "RF.WriteHeaders = true;",
          "RF.Precision = 16;",
          "RF.Add = {" + ", ".join([f"{names[0]}.ElapsedSecs"] + [
              f"{n}.EarthMJ2000Eq.{c}" for n in names for c in ("X", "Y", "Z")]) + "};",
          "",
          "BeginMissionSequence;",
          f"Propagate Synchronized Prop({', '.join(names)}) {{{names[0]}.ElapsedSecs = {args.duration:g}}};",
          ""]
    path = os.path.join(args.out, "edrs_validation.script")
    open(path, "w").write("\n".join(s))
    print("GMAT script written to", path)
    print("ReportFile will be", report)


if __name__ == "__main__":
    main()
